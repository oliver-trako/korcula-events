function translateEventText(text, lang) {
  if (!text || lang === "en" || lang === "hr" || !EVENT_TRANSLATION_RULES[lang]) return text || "";
  let out = text;
  EVENT_TRANSLATION_RULES[lang].forEach(([from, to]) => {
    out = out.split(from).join(to);
  });
  return out;
}
